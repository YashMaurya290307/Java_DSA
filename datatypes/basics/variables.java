package datatypes.basics;
public class variables {
  public static void main(String[] args) {
    int x = 7;
    System.out.println(x+7);
    x = x+2;
    System.out.println(x);
    int y;//declaration
    y=20;//initialization
    System.out.println(x+y);
    System.out.println(x*y);
    y = y-10;
    System.out.println(y);
  }
}
